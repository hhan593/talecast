const STRINGS: Record<Locale, Partial<Record<StringKey, string>>> = { zh, en };

let currentLocale: Locale = 'zh';
const listeners = new Set<(locale: Locale) => void>();

export function setLocale(locale: Locale): void {
  if (currentLocale === locale) return;
  currentLocale = locale;
  for (const listener of listeners) listener(locale);
}

/** 语言变更订阅（useI18n 重渲驱动） */
export function subscribeLocale(listener: (locale: Locale) => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function getLocale(): Locale {
  return currentLocale;
}

/** 诊断：返回某语言缺失的键。缺失键会静默回退中文，属于用户可见缺陷，测试据此兜底。 */
export function missingTranslations(locale: Locale): StringKey[] {
  const target = STRINGS[locale];
  return (Object.keys(STRINGS.zh) as StringKey[]).filter((key) => !target[key]);
}

/**
 * 指定语言的翻译（React 侧统一走这个：以组件 state 为准，不依赖模块单例时序）。
 * 缺失键回退中文，再回退键名；支持 {name} 占位符插值。
 */
export function translate(
  locale: Locale,
  key: StringKey,
  params?: Record<string, string | number>,
): string {
  const raw = STRINGS[locale][key] ?? STRINGS.zh[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

/** 模块级翻译：供非 React 的纯函数/常量表使用 */
export function t(key: StringKey, params?: Record<string, string | number>): string {
  return translate(currentLocale, key, params);
}

/** 解析设置值 → locale（system 用设备区域，非中英环境回退英文） */
export function resolveLocale(setting: LanguageSetting | null): Locale {
  if (setting === 'zh') return 'zh';
  if (setting === 'en') return 'en';
  return systemLocale();
}

/**
 * 设备区域：Hermes 自带 Intl，直接用 resolvedOptions（避免为取语言新增原生依赖）；
 * 取不到时退回 navigator.language，再退回中文。
 */
function systemLocale(): Locale {
  try {
    const resolved = new Intl.DateTimeFormat().resolvedOptions().locale;
    if (resolved) return resolved.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch {
    // Intl 不可用时走 navigator
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language : '';
  if (nav) return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  return 'zh';
}
